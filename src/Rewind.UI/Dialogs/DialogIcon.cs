namespace Rewind.UI.Dialogs;

/// <summary>The picture beside a dialog's message, as on a Windows 98 message box.</summary>
public enum DialogIcon
{
    /// <summary>A speech balloon with a blue i, for news the clerk only reads.</summary>
    Info,

    /// <summary>A yellow triangle with an exclamation mark. Plays the error chord.</summary>
    Warning,

    /// <summary>A red circle with a white X. Plays the error chord.</summary>
    Error,
}
